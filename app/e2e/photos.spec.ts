import { test, expect } from '@playwright/test'

// Run against an expendable local core with PHOTO_E2E_FOLDER pointing to
// three synthetic JPEGs (family-wide.jpg, portrait.jpg, travel.jpg).
test('photo folder to search, comparison and inspector', async ({ page, request }) => {
  const folder = process.env.PHOTO_E2E_FOLDER
  test.skip(!folder, 'Needs the documented synthetic photo fixture and a disposable core')
  const failures: string[] = []
  page.on('pageerror', (error) => failures.push(error.message))
  await page.goto('/photos')
  const enable = page.getByRole('button', { name: 'Enable Photos', exact: true })
  const status = await (await request.get('/api/photos/status')).json()
  if (!status.enabled) await enable.click()
  await expect(page.getByRole('region', { name: 'Lightroom connection', exact: true })).toBeVisible()
  const setup = page.getByRole('region', { name: 'Photo setup', exact: true })
  if (!await setup.isVisible()) await page.getByRole('button', { name: 'Photo setup', exact: true }).click()
  await setup.getByRole('button', { name: /Choose your photos/ }).click()
  await setup.getByRole('button', { name: /^Photo folder/ }).click()
  await page.getByLabel('Folder on this computer').fill(folder!)
  await page.getByRole('button', { name: 'Index folder', exact: true }).click()
  await expect.poll(async () => (await (await request.get('/api/photos/status')).json()).counts.ready ?? 0).toBe(3)
  await page.getByRole('button', { name: 'Close photo setup' }).click()
  await expect(page.getByRole('button', { name: 'Inspect family-wide.jpg', exact: true })).toBeVisible()
  // React Aria visually clips its native input. Exercise keyboard access.
  await page.getByRole('checkbox', { name: 'Select family-wide.jpg', exact: true }).press('Space')
  await page.getByRole('checkbox', { name: 'Select portrait.jpg', exact: true }).press('Space')
  await page.getByRole('button', { name: 'Compare up to four' }).click()
  await expect(page.getByRole('button', { name: 'Inspect travel.jpg', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Inspect portrait.jpg', exact: true }).click()
  const inspector = page.getByRole('complementary', { name: 'Photograph details' })
  await expect(inspector.getByRole('heading', { name: 'portrait.jpg' })).toBeVisible()
  await expect(inspector.getByText('400 × 600', { exact: true })).toBeVisible()
  const image = inspector.getByRole('img', { name: 'portrait.jpg', exact: true })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((img) => (img as HTMLImageElement).naturalWidth)).toBe(400)
  await inspector.getByRole('button', { name: 'Analysis', exact: true }).click()
  const pane = inspector.getByRole('region', { name: 'Scrollable photograph details' })
  const header = inspector.getByRole('heading', { name: 'portrait.jpg' })
  const headerTop = (await header.boundingBox())!.y
  const gallery = page.locator('main > div').first()
  const galleryTop = await gallery.evaluate(el => el.scrollTop)
  await pane.hover()
  await page.mouse.wheel(0, 600)
  await expect.poll(() => pane.evaluate(el => el.scrollTop)).toBeGreaterThan(100)
  expect(await gallery.evaluate(el => el.scrollTop)).toBe(galleryTop)
  expect((await header.boundingBox())!.y).toBe(headerTop)
  await pane.focus()
  await pane.press('End')
  await expect(inspector.getByRole('heading', { name: 'Still needs visual judgement' })).toBeVisible()
  await page.screenshot({ path: '/tmp/metachlorian-photo-analysis.png' })
  await pane.press('Home')
  await inspector.getByRole('button', { name: 'Overview', exact: true }).click()
  await inspector.getByRole('button', { name: 'Open large preview' }).click()
  await expect(page.getByRole('dialog', { name: 'portrait.jpg' })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await expect(inspector).toBeVisible()
  await page.setViewportSize({ width: 768, height: 700 })
  await inspector.getByRole('button', { name: 'Analysis', exact: true }).click()
  await pane.hover()
  await page.mouse.wheel(0, 500)
  await expect.poll(() => pane.evaluate(el => el.scrollTop)).toBeGreaterThan(100)
  await page.screenshot({ path: '/tmp/metachlorian-photo-inspector-tablet.png' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await inspector.getByRole('button', { name: 'Next photograph' }).click()
  await expect(inspector.getByRole('heading', { name: 'portrait.jpg', exact: true })).toHaveCount(0)
  await inspector.getByRole('button', { name: 'Previous photograph' }).click()
  await expect(inspector.getByRole('heading', { name: 'portrait.jpg', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/metachlorian-photos-library.png' })
  await expect(page.getByRole('button', { name: 'Prepare virtual copies' })).toBeDisabled()
  await page.getByRole('button', { name: 'Clear selection' }).click()
  await page.getByLabel('Find photographs', { exact: true }).fill('travel')
  await page.getByRole('button', { name: 'Find photos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Inspect travel.jpg', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Inspect family-wide.jpg', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 768, height: 1024 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/metachlorian-photos-tablet.png' })
  expect(failures).toEqual([])
})

test('setup proves a Lightroom response instead of mistaking copied files for a connection', async ({ page, request }) => {
  const baseline = await (await request.get('/api/photos/status')).json()
  const status = { ...baseline, enabled: true, counts: {}, coverage: { total: 0, analysed: 0, needs_attention: 0, linked: 0, folder_only: 0 }, models: [],
    connector: { ...baseline.connector, files_copied: true, files_current: true },
    lightroom: { connected: false, can_edit: false, label: 'Connect Lightroom', message: 'Open Lightroom and choose Start connection in the plug-in panel.' } }
  await page.route('**/api/photos/status', (route) => route.fulfill({ json: status }))
  await page.route('**/api/photos/search', (route) => route.fulfill({ json: { results: [], total: 0, next_cursor: null } }))
  await page.route('**/api/photos/jobs', (route) => route.fulfill({ json: { jobs: [] } }))
  let checks = 0
  await page.route('**/api/photos/connector/check', (route) => {
    checks++
    if (checks > 1) Object.assign(status.lightroom, { connected: true, can_edit: true, label: 'Lightroom connected', catalog: { name: 'Family', version: '14.2' }, connector_version: '0.2.0', checked_at: Date.now() / 1000, message: 'Lightroom answered successfully.' })
    return route.fulfill({ json: status })
  })
  await page.goto('/photos')
  const setup = page.getByRole('region', { name: 'Photo setup', exact: true })
  await expect(setup.getByRole('button', { name: /^Lightroom catalogue/ })).toBeVisible()
  await page.screenshot({ path: '/tmp/metachlorian-photos-first-run.png' })
  await setup.getByRole('button', { name: 'Set up Lightroom', exact: true }).click()
  await expect(setup.getByRole('heading', { name: 'Connector files are ready' })).toBeVisible()
  await expect(setup.getByText('Lightroom editing needs setup', { exact: false })).toBeVisible()
  await setup.getByRole('button', { name: 'Check connection' }).click()
  await expect(page.getByRole('alert')).toContainText('Start connection')
  await expect(page.getByRole('region', { name: 'Lightroom connection', exact: true })).not.toContainText('Lightroom connected')
  await setup.getByRole('button', { name: 'Check connection' }).click()
  await expect(setup.getByText('Classic 14.2 · Family · connector 0.2.0')).toBeVisible()
  await expect(setup.getByText('Lightroom editing ready for this account', { exact: false })).toBeVisible()
  await page.screenshot({ path: '/tmp/metachlorian-photos-connected.png' })
  await setup.getByRole('button', { name: 'Set up your agent' }).click()
  await expect(setup.getByRole('link', { name: 'Settings → API tokens for agents' })).toHaveAttribute('href', '/settings/tokens')
  await expect(setup.locator('pre')).toContainText('bearer_token_env_var = "METACHLORIAN_TOKEN"')
  await expect(setup.getByRole('button', { name: 'Copy example brief' })).toBeVisible()
})

test('RAW preview shows the real cause and retries after repair', async ({ page, request }) => {
  const baseline = await (await request.get('/api/photos/status')).json()
  const photo = { uid: 'raw-fixture', filename: 'DSC07418.ARW', revision: 'folder-1', availability: 'original', capture_time: null, rating: 0, status: 'pending', width: null, height: null, burst_id: null, is_virtual: false, copy_name: '' }
  await page.route('**/api/photos/status', (route) => route.fulfill({ json: { ...baseline, enabled: true, coverage: { ...baseline.coverage, total: 1 }, models: [] } }))
  await page.route('**/api/photos/search', (route) => route.fulfill({ json: { results: [photo], total: 1, next_cursor: null } }))
  await page.route('**/api/photos/raw-fixture', (route) => route.fulfill({ json: { ...photo, metadata: {}, keywords: [], evidence: {}, faces: [], variants: [] } }))
  let repaired = false
  await page.route('**/api/photos/raw-fixture/preview?*', (route) => repaired ? route.fulfill({ contentType: 'image/png', body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1cAAAAASUVORK5CYII=', 'base64') }) : route.fulfill({ status: 503, json: { detail: 'RAW decoder unavailable. Connect Lightroom to use the catalogue preview.' } }))
  await page.goto('/photos')
  const close = page.getByRole('button', { name: 'Close photo setup' })
  if (await close.isVisible()) await close.click()
  await page.getByRole('button', { name: 'Inspect DSC07418.ARW', exact: true }).click()
  const inspector = page.getByRole('complementary', { name: 'Photograph details' })
  await expect(inspector.getByText('RAW decoder unavailable. Connect Lightroom to use the catalogue preview.')).toBeVisible()
  repaired = true
  await inspector.getByRole('button', { name: 'Retry preview' }).click()
  const image = inspector.getByRole('img', { name: 'DSC07418.ARW', exact: true })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((el) => (el as HTMLImageElement).naturalWidth)).toBe(1)
})
