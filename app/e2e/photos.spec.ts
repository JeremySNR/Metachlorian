test('Edits separates editing work and reviews source alongside the rendered revision', async ({ page, request }) => {
  const baseline = await (await request.get('/api/photos/status')).json()
  await page.route('**/api/photos/status', route => route.fulfill({ json: { ...baseline, enabled: true, coverage: { ...baseline.coverage, total: 2 }, lightroom: { ...baseline.lightroom, connected: true, can_edit: true } } }))
  await page.route('**/api/photos/search', route => route.fulfill({ json: { results: [], total: 0, next_cursor: null } }))
  await page.route('**/api/photos/jobs', route => route.fulfill({ json: { jobs: [
    { uid: 'edit-job', kind: 'apply', status: 'done', error: null, result: { session_id: 'session', photo_id: 'copy', source_photo_id: 'source', revision: 'edited-revision' } },
    { uid: 'index-job', kind: 'folder', status: 'done', error: null, result: { processed: 2, total: 2 } },
  ] } }))
  await page.route('**/api/photos/*/preview?*', route => route.fulfill({ contentType: 'image/png', body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1cAAAAASUVORK5CYII=', 'base64') }))
  let saved: { selections?: { session_id: string; reviewed_revision: string }[]; collection?: string } | undefined
  await page.route('**/api/photos/edits/finish', route => { saved = route.request().postDataJSON(); return route.fulfill({ json: { uid: 'save-job' } }) })
  await page.goto('/photos')
  await page.getByRole('navigation', { name: 'Photo views' }).getByRole('button', { name: 'Edits', exact: true }).click()
  await expect(page.getByText('Folder indexing', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Review edit', exact: true }).click()
  const review = page.getByRole('region', { name: 'Review Lightroom edit' })
  await expect(review.getByRole('img', { name: 'Source photograph', exact: true })).toBeVisible()
  await expect(review.getByRole('img', { name: 'Rendered Lightroom edit', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/metachlorian-photo-edit-review.png' })
  await review.getByRole('textbox', { name: 'Lightroom collection' }).fill('Warm family moments')
  await review.getByRole('button', { name: 'Save reviewed copy', exact: true }).click()
  await expect.poll(() => saved?.collection).toBe('Warm family moments')
  expect(saved?.selections).toEqual([{ session_id: 'session', reviewed_revision: 'edited-revision' }])
  await page.getByRole('navigation', { name: 'Photo views' }).getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.getByText('Folder indexing', { exact: true })).toBeVisible()
})
